"""
Phase 8: Loss & Compensation Recommendation Service
Explainable, deterministic financial policy engine separating physical damage
loss estimates from recommended provisional relief compensation.
"""
import json
from typing import Dict, Tuple

POLICY_NAME = "National Disaster Relief & Property Assistance Policy"
POLICY_VERSION = "2026.1"

# Coverage limits by property type
MAX_COVERAGE_LIMITS = {
    "Residential": 2500000.0,  # ₹25 Lakhs
    "Commercial": 5000000.0,   # ₹50 Lakhs
    "Agricultural": 1500000.0, # ₹15 Lakhs
    "Industrial": 7500000.0,   # ₹75 Lakhs
}

DEFAULT_FALLBACK_VALUE = 800000.0  # ₹8 Lakhs baseline assumption if undeclared


def calculate_compensation_breakdown(
    declared_value: float | None,
    damage_score: float,
    severity_category: str,
    property_type: str = "Residential",
    disaster_type: str = "Flood",
) -> Dict:
    """
    Computes an explainable, deterministic compensation recommendation:
    1. Validates financial inputs and determines effective declared value.
    2. Calculates Estimated Loss based strictly on physical damage severity and damage ratio
       (NEVER using image similarity scores).
    3. Calculates policy deductible (minimum ₹15,000 or 5% of loss, max ₹50,000).
    4. Applies statutory coverage limits by property type.
    5. Returns transparent, itemized calculation breakdown with provisional notice.
    """
    effective_value = float(declared_value) if declared_value and declared_value > 0 else DEFAULT_FALLBACK_VALUE
    max_cap = MAX_COVERAGE_LIMITS.get(property_type, MAX_COVERAGE_LIMITS["Residential"])

    # 1. Calculate Estimated Loss based strictly on physical damage severity
    if severity_category == "no_damage" or damage_score < 0.10:
        loss_multiplier = 0.0
        estimated_loss = 0.0
        deductible = 0.0
        provisional_compensation = 0.0
        loss_rationale = "No structural damage identified in photographic evidence."
    elif severity_category == "minor_damage":
        # Scale between 10% and 30% of property value
        scaled_ratio = min(0.30, max(0.10, damage_score))
        loss_multiplier = scaled_ratio
        estimated_loss = round(effective_value * loss_multiplier, 2)
        loss_rationale = f"Minor cosmetic and localized repair required (multiplier: {loss_multiplier:.1%})."
    elif severity_category == "major_damage":
        # Scale between 35% and 70% of property value
        scaled_ratio = min(0.70, max(0.35, damage_score))
        loss_multiplier = scaled_ratio
        estimated_loss = round(effective_value * loss_multiplier, 2)
        loss_rationale = f"Major structural compromise requiring extensive restoration (multiplier: {loss_multiplier:.1%})."
    else:  # destroyed
        # Scale between 75% and 100% of property value
        scaled_ratio = min(1.00, max(0.75, damage_score))
        loss_multiplier = scaled_ratio
        estimated_loss = round(effective_value * loss_multiplier, 2)
        loss_rationale = f"Total destruction / irreparable foundation collapse (multiplier: {loss_multiplier:.1%})."

    # 2. Calculate Deductible & Policy Net
    if estimated_loss > 0:
        # Standard statutory deductible: 5% of estimated loss, minimum ₹15,000, capped at ₹50,000
        raw_deductible = max(15000.0, estimated_loss * 0.05)
        deductible = min(50000.0, round(raw_deductible, 2))
        subtotal_after_deductible = max(0.0, estimated_loss - deductible)
        provisional_compensation = min(subtotal_after_deductible, max_cap)
    else:
        deductible = 0.0
        provisional_compensation = 0.0

    cap_applied = (estimated_loss - deductible) > max_cap

    breakdown = {
        "policy_name": POLICY_NAME,
        "policy_version": POLICY_VERSION,
        "property_type": property_type,
        "disaster_type": disaster_type,
        "declared_property_value": effective_value,
        "damage_severity_category": severity_category,
        "physical_damage_ratio": damage_score,
        "damage_multiplier": loss_multiplier if severity_category != "no_damage" else 0.0,
        "loss_rationale": loss_rationale,
        "gross_estimated_loss": estimated_loss,
        "deductible_amount": deductible,
        "deductible_formula": "min(₹50,000, max(₹15,000, 5% of Estimated Loss))",
        "maximum_policy_limit": max_cap,
        "cap_applied": cap_applied,
        "recommended_provisional_compensation": round(provisional_compensation, 2),
        "is_provisional": True,
        "officer_review_notice": (
            "PROVISIONAL ESTIMATE: This recommended figure is generated by rule-based policy formula "
            "as decision-support guidance. Final claim settlement requires authorized human verification "
            "and on-site documentation review. No automatic funds transfer is triggered."
        ),
    }

    return {
        "estimated_loss": estimated_loss,
        "deductible": deductible,
        "max_coverage_limit": max_cap,
        "recommended_compensation": round(provisional_compensation, 2),
        "policy_name": POLICY_NAME,
        "policy_version": POLICY_VERSION,
        "breakdown": breakdown,
    }
